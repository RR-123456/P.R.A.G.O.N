def _safe_extract(zf: zipfile.ZipFile, dest: Path):
    dest = dest.resolve()
    for member in zf.infolist():
        member_path = (dest / member.filename).resolve()
        if not str(member_path).startswith(str(dest)):
            raise ValueError(f"Unsafe path in zip: {member.filename}")
    zf.extractall(dest)


def _flatten_single_wrapper_dir(src: Path):
    """Many zips wrap everything in one top-level folder (GitHub-style
    'myproject-main/'). If that's the only thing in src, hoist its contents
    up a level so requirements.txt/package.json etc. are found at src/."""
    entries = list(src.iterdir())
    if len(entries) == 1 and entries[0].is_dir():
        wrapper = entries[0]
        for item in wrapper.iterdir():
            shutil.move(str(item), str(src / item.name))
        wrapper.rmdir()


def _detect_project(src: Path) -> dict:
    """Best-effort guess of runtime/install/start/serves_http when no manifest
    is present. Deliberately conservative — an integration that lands as
    runtime 'unknown' with no start command just can't be started until the
    user supplies (or edits) an integration.json; it's still browsable/deletable."""
    has = lambda name: (src / name).exists()
    files = {p.name for p in src.glob("*")}

    if has("package.json"):
        try:
            pkg = json.loads((src / "package.json").read_text(encoding="utf-8"))
        except Exception:
            pkg = {}
        start_script = (pkg.get("scripts") or {}).get("start")
        entry = pkg.get("main") or "index.js"
        start = "npm start" if start_script else f"node {entry}"
        serves_http = _greps_for_server(src, extensions=(".js",))
        return {
            "runtime": "node", "install": "npm install", "start": start,
            "serves_http": serves_http,
            "description": pkg.get("description") or f"Node.js project ({pkg.get('name', src.name)}).",
        }

    if has("requirements.txt") or has("pyproject.toml") or has("setup.py") or any(f.endswith(".py") for f in files):
        entry = None
        for candidate in ("app.py", "main.py", "server.py", "run.py"):
            if has(candidate):
                entry = candidate
                break
        if not entry:
            py_files = list(src.glob("*.py"))
            entry = py_files[0].name if py_files else None
        install = "pip install -r requirements.txt" if has("requirements.txt") else ""
        start = f"python {entry}" if entry else ""
        serves_http = _greps_for_server(src, extensions=(".py",))
        return {
            "runtime": "python", "install": install, "start": start,
            "serves_http": serves_http,
            "description": f"Python project (entry: {entry or 'unknown'}).",
        }

    return {
        "runtime": "unknown", "install": "", "start": "",
        "serves_http": False,
        "description": "Unrecognized project layout — couldn't auto-detect how to run this. "
                        "Add an integration.json manifest to make it runnable.",
    }


_SERVER_HINTS = (
    "app.run(", "Flask(", "FastAPI(", "uvicorn.run(", "runserver",
    "app.listen(", "createServer(", "express()", ".listen(",
)


def _greps_for_server(src: Path, extensions: tuple[str, ...], max_files: int = 40) -> bool:
    """Cheap heuristic: does this project look like it starts an HTTP server?
    Only used to decide serves_http when no manifest says so explicitly."""
    checked = 0
    for path in src.rglob("*"):
        if path.suffix not in extensions or "node_modules" in path.parts or "venv" in path.parts:
            continue
        checked += 1
        if checked > max_files:
            break
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if any(hint in text for hint in _SERVER_HINTS):
            return True
    return False
