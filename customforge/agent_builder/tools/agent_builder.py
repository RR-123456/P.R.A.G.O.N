FINAL_RE = re.compile(r"Final Answer:\\s*(.*)", re.DOTALL)
ACTION_RE = re.compile(r"Action:\\s*([a-zA-Z_]+)\\s*\\nAction Input:\\s*(\\{.*\\})", re.DOTALL)
THOUGHT_RE = re.compile(r"Thought:\\s*(.*?)(?=\\nAction:|\\nFinal Answer:|\\Z)", re.DOTALL)


def _tool_descriptions():
    lines = []
    for tool_id in ALLOWED_TOOLS:
        meta = TOOL_REGISTRY.get(tool_id)
        if not meta:
            continue
        field_list = ", ".join(f'"{f["name"]}"' for f in meta.get("fields", []))
        lines.append(f"- {tool_id}: {meta['description']}  Parameters: {field_list}")
    return "\n".join(lines)


def _build_prompt(scratchpad: str) -> str:
    return f"""You are an autonomous agent working step by step toward a goal.

Available tools:
{_tool_descriptions()}

Respond with EXACTLY one of these two formats, nothing else:

Thought: <your reasoning about what to do next>
Action: <one tool id from the list above, exactly as written>
Action Input: <a single JSON object with that tool's parameters>

OR, once you have enough information to fully answer the goal:

Thought: <your reasoning>
Final Answer: <the complete answer to the goal>

Goal: {GOAL}
{scratchpad}"""


def _extract_json_object(text: str):
    if not text:
        return None
    idx = text.find("{")
    if idx == -1:
        return None
    decoder = json.JSONDecoder()
    try:
        obj, _ = decoder.raw_decode(text[idx:])
        return obj
    except Exception:
        return None


def _parse_step(text: str) -> dict:
    thought_match = THOUGHT_RE.search(text)
    thought = thought_match.group(1).strip() if thought_match else ""

    final_idx = text.find("Final Answer:")
    action_idx = text.find("Action:")
    if final_idx != -1 and (action_idx == -1 or final_idx < action_idx):
        final_match = FINAL_RE.search(text)
        if final_match:
            return {"thought": thought, "final_answer": final_match.group(1).strip()}

    action_match = ACTION_RE.search(text)
    if action_match:
        return {
            "thought": thought,
            "action": action_match.group(1).strip(),
            "action_input": _extract_json_object(action_match.group(2)),
            "raw_input": action_match.group(2).strip(),
        }

    return {"thought": thought or text.strip(), "unparsed": text.strip()}


def run_agent():
    model = get_model(DEFAULT_MODEL)
    scratchpad = ""
    seen_calls = set()
    transcript = []

    print("=" * 60)
    print("AUTONOMOUS AGENT")
    print("=" * 60)
    print(f"Goal: {GOAL}")
    print(f"Tools: {', '.join(ALLOWED_TOOLS)}")
    print(f"Model: {DEFAULT_MODEL}")
    print(f"Max steps: {DEFAULT_MAX_ITERATIONS}")
    print("=" * 60)

    for step_num in range(1, DEFAULT_MAX_ITERATIONS + 1):
        prompt = _build_prompt(scratchpad)

        try:
            resp = model.generate_content(prompt)
            text = (resp.text or "").strip()
        except Exception as e:
            print(f"\nModel error: {e}")
            transcript.append({"step": step_num, "error": str(e)})
            break

        print(f"\n--- Step {step_num} ---")

        parsed = _parse_step(text)

        if "final_answer" in parsed:
            print(f"Thought: {parsed['thought']}")
            print(f"Final Answer: {parsed['final_answer']}")
            transcript.append({
                "step": step_num,
                "thought": parsed["thought"],
                "final_answer": parsed["final_answer"],
            })
            _save_transcript(transcript)
            return parsed["final_answer"]

        action = parsed.get("action")
        if not action:
            print("Unparsed response - retrying...")
            scratchpad += (
                f"\n{text}\n"
                f"Observation: Your last response didn't follow the required format. Try again.\n"
            )
            transcript.append({"step": step_num, "raw": text, "error": "unparsed"})
            continue

        if action not in ALLOWED_TOOLS:
            obs = f"Unknown tool '{action}'. Available: {', '.join(ALLOWED_TOOLS)}"
            print(f"{obs}")
            scratchpad += f"\nThought: {parsed['thought']}\nAction: {action}\nObservation: {obs}\n"
            transcript.append({"step": step_num, "thought": parsed["thought"], "action": action, "observation": obs})
            continue

        action_input = parsed.get("action_input") or {}
        call_sig = (action, json.dumps(action_input, sort_keys=True))

        if call_sig in seen_calls:
            obs = "You already made this exact call. Use a different action or give your Final Answer."
            print(f"{obs}")
        else:
            seen_calls.add(call_sig)
            print(f"{action}({json.dumps(action_input)})")
            try:
                obs = run_tool(action, dict(action_input))
            except Exception as e:
                obs = f"Tool error: {e}"
            print(f"{obs[:500]}{'...' if len(obs) > 500 else ''}")

        scratchpad += (
            f"\nThought: {parsed['thought']}\n"
            f"Action: {action}\n"
            f"Action Input: {json.dumps(action_input)}\n"
            f"Observation: {obs[:1500]}\n"
        )
        transcript.append({
            "step": step_num,
            "thought": parsed["thought"],
            "action": action,
            "action_input": action_input,
            "observation": obs[:1500],
        })

    print(f"\nStopped after {DEFAULT_MAX_ITERATIONS} steps without a Final Answer.")
    _save_transcript(transcript)
    return None


