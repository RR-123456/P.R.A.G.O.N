def build_agent(parameters: dict = None, **kwargs) -> str:
    from .registry import TOOL_REGISTRY  # lazy import — see note at top of file
    params = parameters or {}
    goal = (params.get("goal") or params.get("description") or "No goal set").strip()
    model = params.get("model", "auto").strip()
    max_iter = int(params.get("max_iterations", 10))
    output_path = params.get("output_path", "").strip()

    real_tools = [t for t in TOOL_REGISTRY.keys() if t != "gemini_agent"]
    allowed = params.get("allowed_tools") or real_tools
    allowed = [t for t in allowed if t in real_tools] or real_tools

    code = _generate_agent_code(goal, allowed, model, max_iter)

    if output_path:
        save_path = Path(output_path)
        if not save_path.is_absolute():
            save_path = Path.home() / "Desktop" / save_path
    else:
        save_path = Path.home() / "Desktop" / "agent_generated.py"

    save_path.parent.mkdir(parents=True, exist_ok=True)
    save_path.write_text(code, encoding="utf-8")

    # Also drop a copy in exports/ under a unique name, so it can be pulled
    # down as a browser download via /api/export-agent/<filename> — see the
    # EXPORTS_DIR comment above for why this exists alongside save_path.
    EXPORTS_DIR.mkdir(parents=True, exist_ok=True)
    export_name = f"{_slugify(goal)}-{uuid.uuid4().hex[:8]}.py"
    export_path = EXPORTS_DIR / export_name
    export_path.write_text(code, encoding="utf-8")

    preview = code[:800] + ("\n..." if len(code) > 800 else "")
    parts = [
        "Standalone agent generated and saved to:\n  " + str(save_path) + "\n\n",
        "Goal: " + goal + "\n",
        "Tools: " + ", ".join(allowed) + "\n",
        "Model: " + model + "\n",
        "Max steps: " + str(max_iter) + "\n\n",
        "Code preview:\n" + "-"*40 + "\n" + preview + "\n" + "-"*40 + "\n\n",
        'Run it: python "' + str(save_path) + '"\n\n',
        "Export URL: /api/export-agent/" + export_name,
    ]
    return "".join(parts)
